#!/usr/bin/env bash
# Emit the remote deploy program: the deploy group, then the libraries, then
# the program itself.
#
# This is the only supported entry point. The workflow streams its output to
# the deploy host:
#   bash scripts/deploy/bundle.sh | ssh ... "… bash -s"
# so the server needs no checkout of the repository. Tests stream it the same
# way: `bash scripts/deploy/bundle.sh | bash -s`.
#
# The deploy group comes from this script's own environment and is written as
# safely quoted shell assignments, so the workflow never hand-serializes the
# values into the remote command. The libraries follow; remote.sh must never be
# run on its own.
set -euo pipefail

deploy_group=(IMAGE_TAG IMAGE_REPOSITORY IMAGE_SOURCE DEPLOY_PATH PORT GHCR_USER)
for name in "${deploy_group[@]}"; do
  if [ -z "${!name:-}" ]; then
    printf '::error::Missing deploy configuration: %s\n' "$name" >&2
    exit 1
  fi
done

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
lib_dir="$script_dir/../lib"

printf '%s\n' '#!/usr/bin/env bash'
printf '# Generated by scripts/deploy/bundle.sh; do not edit.\n'
for name in "${deploy_group[@]}"; do
  printf '%s=%q\n' "$name" "${!name}"
done
cat "$lib_dir/health.sh" "$lib_dir/registry-error.sh" "$script_dir/remote.sh"
