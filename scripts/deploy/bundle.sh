#!/usr/bin/env bash
# Emit the remote deploy program with its libraries inlined.
#
# The workflow streams this to the deploy host:
#   bash scripts/deploy/bundle.sh | ssh ... "… bash -s"
# so the server needs no checkout of the repository. Tests stream it the same
# way: `bash scripts/deploy/bundle.sh | bash -s`.
#
# The libraries come first; remote.sh only sources them when it is run directly
# from a checkout, so the streamed program never reads repository paths on the
# host.
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
lib_dir="$script_dir/../lib"

printf '%s\n' '#!/usr/bin/env bash'
printf '# Generated by scripts/deploy/bundle.sh; do not edit.\n'
cat "$lib_dir/health.sh" "$lib_dir/registry-error.sh" "$script_dir/remote.sh"
